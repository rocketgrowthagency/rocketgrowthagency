#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════════════════════════
// build-mockup-registry.mjs — writes memory/reference_mockup_registry.md
//
// 🔴 WHY (Chris, 2026-10-08): "make sure all work and mockups and steps we do … are all saved in
// memory and the system hardened so we dont lose any work and regress or forget." An audit that day
// found 26 of 73 mockups named in NO memory file — a future session could not find them, or tell
// whether they were approved and built.
//
// 🔑 GENERATED, NOT HAND-KEPT. A list somebody has to remember to update is the thing that drifted.
// Every mockup in reports/mockups gets a row from its own facts: <title>, the date git first saw it,
// the commit that added it, and which memory files cite it. Run by the nightly sweep before
// check-every-mockup-is-in-memory, and by hand after a mockup is published.
//
// 🔴 It writes into the memory dir with fs — which BYPASSES the PostToolUse mirror hook — so it
// writes the git-versioned mirror (.claude/memory) itself. → feedback_writing_memory_with_bash_bypasses_the_mirror_hook
// ═══════════════════════════════════════════════════════════════════════════════════════════════
import fs from "node:fs";
import { execFileSync } from "node:child_process";

const SITE = process.env.APPROVAL_ARCHIVE_SITE_DIR || "/Users/chris/RGA/Rocket Growth Agency Website VS Code";
const MEM = process.env.RGA_MEMORY_DIR || "/Users/chris/.claude/projects/-Users-chris-RGA-Rocket-Growth-Agency-Website-VS-Code/memory";
const MIRROR = `${SITE}/.claude/memory`;
const DIR = `${SITE}/reports/mockups`;
const OUT = "reference_mockup_registry.md";
// Files that LIST things are not evidence that a mockup's system was recorded.
const NOT_A_CITATION = new Set([OUT, "reference_gate_catalogue.md", "_audit.log"]);

const git = (...a) => { try { return execFileSync("git", ["-C", SITE, ...a], { encoding: "utf8" }).trim(); } catch { return ""; } };
const mem = fs.readdirSync(MEM).filter((f) => f.endsWith(".md") && !NOT_A_CITATION.has(f))
  .map((f) => ({ f, text: fs.readFileSync(`${MEM}/${f}`, "utf8") }));

const rows = fs.readdirSync(DIR).filter((f) => f.endsWith(".html")).sort().map((f) => {
  const base = f.replace(/\.html$/, "");
  const html = fs.readFileSync(`${DIR}/${f}`, "utf8");
  const title = ((html.slice(0, 8000).match(/<title>([^<]*)<\/title>/i) || [])[1] || "").trim();
  const added = git("log", "--diff-filter=A", "--follow", "--format=%ad|%s", "--date=short", "--", `reports/mockups/${f}`).split("\n").pop() || "";
  const [date = "uncommitted", subject = ""] = added ? added.split("|") : [];
  const cited = mem.filter((m) => m.text.includes(base)).map((m) => m.f.replace(/\.md$/, ""));
  // an artifact id is a 22-char mixed-case token written within a few words after the mockup's name
  const art = (() => {
    for (const m of mem) {
      let i = m.text.indexOf(base);
      while (i !== -1) {
        const win = m.text.slice(i + base.length, i + base.length + 140);
        const id = (win.match(/claude\.ai\/artifact\/([A-Za-z0-9]{20,24})/) || win.match(/\b(?=[A-Za-z0-9]*\d)(?=[A-Za-z0-9]*[A-Z])(?=[A-Za-z0-9]*[a-z])([A-Za-z0-9]{22})\b/) || [])[1];
        if (id) return id;
        i = m.text.indexOf(base, i + 1);
      }
    }
    return "";
  })();
  return { f, base, title, date, subject, cited, art };
});

const cell = (s) => String(s || "").replace(/\|/g, "/").replace(/\n/g, " ");
const lines = [
  "---",
  "name: reference_mockup_registry",
  `description: "GENERATED by scripts/build-mockup-registry.mjs — every mockup in reports/mockups (${rows.length}), with its title, the date and commit that added it, its artifact id when memory records one, and the memory files that cite it. Do not hand-edit; re-run the script."`,
  "metadata:",
  "  type: reference",
  "---",
  "",
  `# 🗂️ EVERY MOCKUP (${rows.length}) — generated ${new Date().toISOString().slice(0, 10)}`,
  "",
  "Do not edit by hand: `node scripts/build-mockup-registry.mjs` (scraper repo). The nightly sweep",
  "rebuilds it, then `check-every-mockup-is-in-memory` fails if a mockup added on/after 2026-10-08",
  "is cited by no system memory file. **Uncited = legacy** (before the gate): the commit subject is",
  "the only record — open the file to see what it proposed.",
  "Artifact links: https://claude.ai/artifact/<id>. Related: [[feedback_how_design_work_gets_done_first_time]]",
  "",
  "| mockup | title | added | commit | artifact | cited by |",
  "|---|---|---|---|---|---|",
  ...rows.slice().sort((a, b) => (b.date || "").localeCompare(a.date || "") || a.f.localeCompare(b.f)).map((r) =>
    `| \`${r.base}\` | ${cell(r.title)} | ${r.date} | ${cell(r.subject).slice(0, 90)} | ${r.art || ""} | ${r.cited.length ? r.cited.map((c) => `[[${c}]]`).join(" ") : "**legacy · uncited**"} |`),
  "",
];
const out = lines.join("\n");
fs.writeFileSync(`${MEM}/${OUT}`, out);
if (fs.existsSync(MIRROR)) fs.writeFileSync(`${MIRROR}/${OUT}`, out);
const uncited = rows.filter((r) => !r.cited.length).length;
console.log(`✅ ${rows.length} mockups registered · ${rows.length - uncited} cited by memory · ${uncited} legacy uncited → ${OUT}${fs.existsSync(MIRROR) ? " (+ mirror)" : ""}`);
